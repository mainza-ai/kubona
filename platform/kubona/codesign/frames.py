"""Frame-block grouping at toy scale (SI IV, exact group action).

The paper groups Pauli operators related by fixed Clifford frames into
blocks of powers of two (address bits index within a block; one rep + frame
controls replaces per-row Select). Toy model (stated): n <= 4 qubits, Paulis
as (x_mask, z_mask) pairs (phase-blind: Y-count parity handled by the
evaluator layer, not here), frames as qubit permutations (exact Clifford
action: permute bit positions). find_blocks() partitions a closed multiset
into orbits under the group generated by the frames; an orbit whose size is
not a power of two is reported ungrouped (cannot take address bits — never
forced into a fake block). Each block verifies: applying the recorded frame
subset to the representative reproduces every member exactly.
"""

from __future__ import annotations

import itertools


def _check_pauli(p: tuple[int, int], n: int) -> None:
    if not isinstance(p, tuple) or len(p) != 2:
        raise ValueError(f"Pauli must be (x_mask, z_mask), got {p!r}: refusing")
    for m in p:
        if not isinstance(m, int) or m < 0 or m >= (1 << n):
            raise ValueError(f"Pauli mask {m!r} outside {n} qubits: refusing")


def apply_perm(p: tuple[int, int], perm: tuple[int, ...]) -> tuple[int, int]:
    """Permute qubit positions in both masks (exact Clifford action)."""
    n = len(perm)
    if sorted(perm) != list(range(n)) or n > 4 or n < 1:
        raise ValueError(f"perm must be a permutation of 0..n-1 (n<=4), got {perm!r}: refusing")
    _check_pauli(p, n)
    x, z = p
    nx = nz = 0
    for i, j in enumerate(perm):
        if (x >> i) & 1:
            nx |= 1 << j
        if (z >> i) & 1:
            nz |= 1 << j
    return (nx, nz)


def _compose(a: tuple[int, ...], b: tuple[int, ...]) -> tuple[int, ...]:
    return tuple(a[b[i]] for i in range(len(a)))


def group_generated(perms: list[tuple[int, ...]]) -> list[tuple[int, ...]]:
    """Closure of the identity under composition (exact, n<=4 so tiny)."""
    if not perms:
        raise ValueError("need at least one frame perm: refusing")
    n = len(perms[0])
    ident = tuple(range(n))
    seen = {ident}
    stack = [ident]
    while stack:
        g = stack.pop()
        for p in perms:
            for h in (_compose(g, p), _compose(p, g)):
                if h not in seen:
                    seen.add(h)
                    stack.append(h)
    return sorted(seen)


def _orbit_partition(paulis: list[tuple[int, int]], elements: list,
                     apply) -> tuple[list[dict], list]:
    """Shared orbit + power-of-two gating + witness reconstruction."""
    remaining = list(paulis)
    blocks: list[dict] = []
    ungrouped: list[tuple[int, int]] = []
    while remaining:
        rep = remaining[0]
        orbit = sorted({apply(rep, g) for g in elements})
        members = [p for p in remaining if p in orbit]
        for m in members:
            remaining.remove(m)
        if len(members) & (len(members) - 1) or len(members) > len(orbit):
            ungrouped.extend(members)
            continue
        rec: dict[str, object] = {}
        for m in members:
            rec[f"{m}"] = next(g for g in elements if apply(rep, g) == m)
        nbits = len(members).bit_length() - 1
        blocks.append({"rep": rep, "members": members, "size": len(members),
                       "addr_bits": nbits, "witnesses": rec})
    return blocks, ungrouped


def find_blocks(paulis: list[tuple[int, int]], perms: list[tuple[int, ...]]) -> dict:
    """Orbit partition with power-of-two gating + reconstruction proof."""
    if not paulis:
        raise ValueError("paulis must be non-empty: refusing")
    n = len(perms[0]) if perms else 0
    if n < 1 or any(len(p) != n or sorted(p) != list(range(n)) for p in perms):
        raise ValueError("perms must share one n<=4: refusing")
    for p in paulis:
        _check_pauli(p, n)
    group = group_generated(perms)
    blocks, ungrouped = _orbit_partition(paulis, group, apply_perm)
    # closure gate: the input multiset must be group-closed (a frame of a
    # table row must itself be a table row) — else the frames do not explain
    # the table and the blocks are unsound. Refuse loudly.
    for b in blocks:
        for m in b["members"]:
            for g in group:
                if apply_perm(m, g) not in b["members"] and apply_perm(m, g) in paulis:
                    raise ValueError("block leaks under group (implementation bug): refusing")
    return {"blocks": blocks, "ungrouped": ungrouped,
            "n_frames": len(group), "closed": not ungrouped}


def _mat_mul(a: tuple[int, ...], b: tuple[int, ...]) -> tuple[int, ...]:
    """GF(2) matrix product (rows as bitmasks): (A*B)[i] = sum_k A[i][k] B[k]."""
    m = len(a)
    out = []
    for i in range(m):
        row, aik = 0, a[i]
        k = 0
        while aik:
            if aik & 1:
                row ^= b[k]
            aik >>= 1
            k += 1
        out.append(row)
    return tuple(out)


def _is_symplectic(mat: tuple[int, ...], n: int) -> bool:
    """M^T Ω M == Ω over GF(2) with Ω = [[0,I],[I,0]] (exact gate)."""
    m = 2 * n
    # columns of M: col j has bit i where row i has bit j
    cols = []
    for j in range(m):
        c = 0
        for i in range(m):
            if (mat[i] >> j) & 1:
                c |= 1 << i
        cols.append(c)
    def _omega(u: int, v: int) -> int:
        xu, zu = u & ((1 << n) - 1), (u >> n) & ((1 << n) - 1)
        xv, zv = v & ((1 << n) - 1), (v >> n) & ((1 << n) - 1)
        return (bin(xu & zv).count("1") + bin(zu & xv).count("1")) & 1
    for i in range(m):
        for j in range(m):
            want = 1 if (i < n) != (j < n) and (i % n) == (j % n) and abs(i - j) == n else 0
            # Ω[i][j] = 1 iff (i<n<=j, i==j-n) or (j<n<=i, j==i-n)
            if _omega(cols[i], cols[j]) != want:
                return False
    return True


def _symplectic(n: int, rows: list[int]) -> tuple[int, ...]:
    mat = tuple(rows)
    if len(mat) != 2 * n or any(r < 0 or r >= (1 << (2 * n)) for r in mat):
        raise ValueError(f"need {2*n} rows of {2*n} bits: refusing {rows!r}")
    if not _is_symplectic(mat, n):
        raise ValueError("matrix is not symplectic (not a Clifford frame): refusing")
    return mat


def perm_frame(perm: tuple[int, ...]) -> tuple[int, ...]:
    """Qubit-permutation frame as a symplectic matrix (embeds apply_perm)."""
    n = len(perm)
    if sorted(perm) != list(range(n)) or n > 4 or n < 1:
        raise ValueError(f"perm must permute 0..n-1 (n<=4), got {perm!r}: refusing")
    rows = [0] * (2 * n)
    for i, j in enumerate(perm):
        rows[j] |= 1 << i
        rows[n + j] |= 1 << (n + i)
    return _symplectic(n, rows)


def hadamard_frame(n: int, i: int) -> tuple[int, ...]:
    """Hadamard frame on qubit i (swaps x_i <-> z_i, exact Clifford)."""
    if not isinstance(n, int) or n > 4 or n < 1 or not (0 <= i < n):
        raise ValueError(f"need n<=4 and 0<=i<n, got n={n!r} i={i!r}: refusing")
    rows = [(1 << k) for k in range(2 * n)]
    rows[i], rows[n + i] = rows[n + i], rows[i]
    return _symplectic(n, rows)


def cnot_frame(n: int, c: int, t: int) -> tuple[int, ...]:
    """CNOT-conjugation frame (x_t ^= x_c, z_c ^= z_t — the exact action)."""
    if not isinstance(n, int) or n > 4 or n < 1:
        raise ValueError(f"need n<=4, got {n!r}: refusing")
    if c == t or not (0 <= c < n and 0 <= t < n):
        raise ValueError(f"need distinct c,t in range, got {c!r},{t!r}: refusing")
    rows = [(1 << k) for k in range(2 * n)]
    rows[t] ^= 1 << c
    rows[n + c] ^= 1 << (n + t)
    return _symplectic(n, rows)


def apply_frame(p: tuple[int, int], mat: tuple[int, ...]) -> tuple[int, int]:
    """Apply a symplectic frame to a Pauli mask pair (phase-blind, stated)."""
    m = len(mat)
    if m % 2 or m > 8 or m < 2:
        raise ValueError(f"frame must be 2n x 2n (n<=4), got {m} rows: refusing")
    n = m // 2
    _check_pauli(p, n)
    v = p[0] | (p[1] << n)
    x = z = 0
    for k in range(n):
        if bin(mat[k] & v).count("1") & 1:
            x |= 1 << k
    for k in range(n):
        if bin(mat[n + k] & v).count("1") & 1:
            z |= 1 << k
    return (x, z)


def symplectic_group(mats: list[tuple[int, ...]]) -> list[tuple[int, ...]]:
    """Closure under GF(2) composition (exact; refuses explosive groups)."""
    if not mats:
        raise ValueError("need at least one frame: refusing")
    m = len(mats[0])
    if any(len(x) != m for x in mats):
        raise ValueError("frames must share one dimension: refusing")
    ident = tuple(1 << k for k in range(m))
    seen = {ident}
    stack = [ident]
    while stack:
        g = stack.pop()
        for f in mats:
            for h in (_mat_mul(g, f), _mat_mul(f, g)):
                if h not in seen:
                    seen.add(h)
                    stack.append(h)
        if len(seen) > 1152:
            raise ValueError("frame group exceeds 1152 (not a toy family): refusing")
    return sorted(seen)


def find_blocks_symplectic(paulis: list[tuple[int, int]],
                           mats: list[tuple[int, ...]]) -> dict:
    """Orbit partition under general Clifford-linear frames (H/CNOT/perms).

    Same gates as find_blocks (power-of-two sizes, witness reconstruction,
    group-closure); the frame family is richer than permutations, so tables
    with X<->Z or CNOT-related Paulis group where perms alone leave
    singletons. Phase-blind (stated): coefficients ride as independent table
    entries, exactly as the paper keeps w_l independent of the Pauli relation.
    """
    if not paulis:
        raise ValueError("paulis must be non-empty: refusing")
    n = len(mats[0]) // 2
    for p in paulis:
        _check_pauli(p, n)
    group = symplectic_group(mats)
    blocks, ungrouped = _orbit_partition(paulis, group, apply_frame)
    for b in blocks:
        for m in b["members"]:
            for g in group:
                if apply_frame(m, g) not in b["members"] and apply_frame(m, g) in paulis:
                    raise ValueError("block leaks under group (implementation bug): refusing")
    return {"blocks": blocks, "ungrouped": ungrouped,
            "n_frames": len(group), "closed": not ungrouped}
