"""Secure Subprocess Execution Sandbox for Autonomous Workloads.

Isolates untrusted or dynamic code generated by agents:
1. AST Import Whitelisting (deny-by-default: only the scientific allowlist;
   os/sys/subprocess/shutil/socket/... refuse, as do dunder-escape and
   introspection bypasses below).
2. OS Resource Limits (setrlimit CPU seconds, max memory, max child processes).
3. Subprocess execution with strict timeout, scrubbed environment, capped
   output, and TemporaryDirectory cleanup (no delete=False + unlink race).

Production posture (Phase-2 hardening, 2026-10-28): the AST + rlimit path is
NOT a security boundary (numpy/ctypes/file-io escapes) — it is a dev-only
hermetic runner. `execute_script` routes: KUBONA_SANDBOX_CONTAINER=1 runs the
pinned container (dev and production); anything else in production (or on an
unknown KUBONA_ENV spelling, which fails closed like console_token()) refuses
with `isolation_required`, and KUBONA_SANDBOX_UNSAFE_LOCAL=1 NEVER re-enables
local execution in production. In dev the flag is REQUIRED for local runs
(only =1 acknowledges dev-only local execution; unset/"" /"0" refuse with
`unsafe_local_disabled` — the historic unset-permits-local default is gone).
"""

