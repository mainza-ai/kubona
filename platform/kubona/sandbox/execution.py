"""Secure Subprocess Execution Sandbox for Autonomous Workloads.

Isolates untrusted or dynamic code generated by agents:
1. AST Import Whitelisting (rejects socket, subprocess, ctypes, pty, shutil, etc.).
2. OS Resource Limits (setrlimit CPU seconds, max memory, max child processes).
3. Subprocess execution with strict timeout and capture.
"""

from __future__ import annotations

import ast
import json
import os
import resource
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from typing import Any, Sequence

# Allowed standard scientific and numerical modules
ALLOWED_MODULES = {
    "math",
    "cmath",
    "random",
    "numpy",
    "scipy",
    "json",
    "dataclasses",
    "typing",
    "collections",
    "itertools",
    "functools",
    "time",
    "kubona",
}

BLOCKED_MODULES = {
    "os",
    "sys",
    "subprocess",
    "shutil",
    "socket",
    "http",
    "urllib",
    "requests",
    "ctypes",
    "pty",
    "fcntl",
    "pwd",
    "grp",
    "signal",
    "posix",
    "builtin",
    "builtins",
}


class SecurityPolicyViolation(RuntimeError):
    pass


@dataclass
class SandboxResult:
    success: bool
    returncode: int
    stdout: str
    stderr: str
    violation: str | None = None


class WorkloadSandbox:
    """Static and dynamic sandbox for agent code execution."""

    def __init__(
        self,
        max_cpu_seconds: int = 5,
        max_memory_mb: int = 512,
        allowed_modules: set[str] | None = None,
    ):
        self.max_cpu_seconds = max_cpu_seconds
        self.max_memory_mb = max_memory_mb
        self.allowed_modules = allowed_modules or ALLOWED_MODULES

    def validate_ast(self, code_str: str) -> None:
        """Inspects Python code AST and rejects forbidden imports or dangerous builtins."""
        try:
            tree = ast.parse(code_str)
        except SyntaxError as e:
            raise SecurityPolicyViolation(f"Syntax error: {e}") from e

        for node in ast.walk(tree):
            # Check import x
            if isinstance(node, ast.Import):
                for alias in node.names:
                    root_pkg = alias.name.split(".")[0]
                    if root_pkg in BLOCKED_MODULES or root_pkg not in self.allowed_modules:
                        raise SecurityPolicyViolation(f"Disallowed import: '{alias.name}'")

            # Check from x import y
            elif isinstance(node, ast.ImportFrom):
                if node.module:
                    root_pkg = node.module.split(".")[0]
                    if root_pkg in BLOCKED_MODULES or root_pkg not in self.allowed_modules:
                        raise SecurityPolicyViolation(f"Disallowed import from: '{node.module}'")

            # Check calls to dangerous builtins like eval, exec, __import__
            elif isinstance(node, ast.Call):
                if isinstance(node.func, ast.Name):
                    if node.func.id in ("exec", "eval", "__import__", "compile", "open"):
                        raise SecurityPolicyViolation(f"Disallowed call to builtin '{node.func.id}()'")

    def execute_script(self, code_str: str, timeout_sec: float = 10.0) -> SandboxResult:
        """Validates AST and executes in an isolated subprocess with resource constraints."""
        try:
            self.validate_ast(code_str)
        except SecurityPolicyViolation as exc:
            return SandboxResult(
                success=False,
                returncode=-1,
                stdout="",
                stderr=str(exc),
                violation=str(exc),
            )

        with tempfile.NamedTemporaryFile("w", suffix=".py", delete=False) as f:
            f.write(code_str)
            script_path = f.name

        def _preexec_fn():
            # CPU time limit
            resource.setrlimit(resource.RLIMIT_CPU, (self.max_cpu_seconds, self.max_cpu_seconds + 1))
            # Memory address space limit (bytes)
            mem_bytes = self.max_memory_mb * 1024 * 1024
            try:
                resource.setrlimit(resource.RLIMIT_AS, (mem_bytes, mem_bytes))
            except (ValueError, OSError):
                pass  # In some macOS environments RLIMIT_AS has restricted ranges

        try:
            proc = subprocess.run(
                [sys.executable, script_path],
                preexec_fn=_preexec_fn,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                text=True,
                timeout=timeout_sec,
            )
            return SandboxResult(
                success=(proc.returncode == 0),
                returncode=proc.returncode,
                stdout=proc.stdout,
                stderr=proc.stderr,
            )
        except subprocess.TimeoutExpired:
            return SandboxResult(
                success=False,
                returncode=-1,
                stdout="",
                stderr=f"Execution timed out after {timeout_sec}s",
                violation="timeout",
            )
        finally:
            if os.path.exists(script_path):
                os.unlink(script_path)
