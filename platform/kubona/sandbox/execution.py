# Calls that refuse even when spelled as bare names (W2.15): code execution,
# dynamic import, file access, module-attribute scraping, and frame
# introspection. getattr/setattr/hasattr are refused outright — in a sandbox,
# getattr-on-modules is the standard import-hook bypass, and no legitimate
# sandboxed workload needs runtime attribute reflection.
_BLOCKED_CALLS = frozenset({
    "exec", "eval", "__import__", "compile", "open",
    "getattr", "setattr", "hasattr", "delattr",
    "globals", "locals", "vars", "dir", "breakpoint", "help",
    "input", "exit", "quit",
    # importlib.import_module spelled as an attribute call (the module itself
    # can never be imported, but the name is refused here too so a smuggled
    # reference still cannot invoke it).
    "import_module",
})

# Benign dunder reads (P1): every OTHER dunder attribute is refused
# (fail-closed over clever — the old comment promised this but the code only
# blocked listed names, so `e.__traceback__`, `m.__self__`, `mod.__loader__`
# all passed). Name/doc/version introspection is harmless and occasionally
# legitimate; every other dunder (`__traceback__`, `__cause__`, `__context__`,
# `__self__`, `__func__`, `__wrapped__`, `__loader__`, `__path__`, ...)
# is a frame/function/module-escape step and refuses. Bare `__name__`
# (e.g. `if __name__ == "__main__"`) is a Name node, not an Attribute, and
# is unaffected.
_BENIGN_DUNDER_ATTRS = frozenset({"__name__", "__doc__", "__version__"})

# Attribute escapes (W2.15): dunder traversal reaches object.__subclasses__()
# and from there every loaded class (file, socket, Popen). Refuse the whole
# dangerous set — and any dunder attribute not on the benign list above is
# refused too (fail-closed over clever).
_BLOCKED_ATTRS = frozenset({
    "__class__", "__bases__", "__mro__", "__subclasses__", "__dict__",
    "__globals__", "__closure__", "__code__", "__builtins__", "__import__",
    "__build_class__", "__base__", "__basicsize__", "__subclasshook__",
    "__weakref__", "__init_subclass__", "__abstractmethods__",
    "gi_frame", "gi_code", "f_locals", "f_globals", "f_code",
    # NumPy/ SciPy file + native escape hatches (2026-10-26 audit P0-4):
    # numpy.ctypeslib reopens libc; fromfile/memmap/load read host files.
    "ctypeslib", "fromfile", "tofile", "memmap", "open_memmap",
    "load", "save", "savez", "savez_compressed", "loadtxt", "savetxt",
    "DataSource",
    # Scientific file-I/O + codegen verbs (P1, 2026-10-28): refused as
    # ATTRIBUTES too, so a smuggled module reference (not just an import)
    # still cannot reach them. scipy.io / numpy.f2py are import-refused
    # above; these cover `np.f2py.run_main` style attribute reach.
    "f2py", "distutils",
    "run_main", "crackfortran",
    "loadmat", "savemat", "mmread", "mmwrite",
    "genfromtxt", "fromregex",
    # Frame / traceback / coroutine reach (P1, 2026-10-28): tb_frame leaks
    # the live frame (and its globals) from any caught exception; f_back
    # walks the whole stack; cr_/ag_frame do the same for coroutines and
    # generators. gi_frame/f_locals/f_globals were already out.
    "tb_frame", "tb_next",
    "f_back", "f_trace",
    "cr_frame", "cr_code", "ag_frame", "ag_code",
})

# Child environment allowlist (W2.15): the child gets ONLY these (copied from
# the parent when present). Everything else — KUBONA_* tokens, BAO_*
# credentials, AWS_*/GH_* secrets, HOME/SSH paths — is dropped. The child
# runs an absolute interpreter path, so it needs no PATH to function; a
# minimal PATH is kept for libc-adjacent lookups only.
_SANDBOX_ENV_ALLOW = frozenset({
    "PATH", "SYSTEMROOT", "LANG", "LC_ALL", "LC_CTYPE", "TZ", "TMPDIR",
    "TEMP", "TMP", "PYTHONHASHSEED", "PYTHONUTF8", "PYTHONIOENCODING",
})

#: Dev spellings that permit the hermetic local runner (with the unsafe-local
#: acknowledgement below). Production AND any unknown spelling (a "prod"
#: typo fails closed, mirroring console_token()'s unknown-value rule in
#: kubona/config.py) refuse local execution — only the container rail runs.
_DEV_ENV_VALUES = frozenset({"", "dev", "test"})

#: Output cap per stream (W2.15): a runaway print must not OOM the supervisor.
MAX_OUTPUT_BYTES = 256 * 1024


# Runtime audit hooks are deliberately NOT installed in the local path:
# importing numpy itself dlopen()s BLAS, so a blanket dlopen ban would break
# legitimate science. Production closes this rail by refusing local
# execution (isolation_required) and using the container path instead.
_SANDBOX_PREAMBLE = ""


class SecurityPolicyViolation(RuntimeError):
    pass


@dataclass
class SandboxResult:
    success: bool
    returncode: int
    stdout: str
    stderr: str
    violation: str | None = None
    truncated: bool = False


def scrubbed_env() -> dict[str, str]:
    """Child environment: allowlist only (W2.15)."""
    return {k: v for k, v in os.environ.items() if k in _SANDBOX_ENV_ALLOW}


def _is_explicit_dev_environment() -> bool:
    """True only for explicit dev spellings ("", dev, test).

    Production AND unknown KUBONA_ENV spellings fail closed (local execution
    refused). A "prod" typo must never silently re-enable the local runner —
    the old check rested on `is_production()` alone, so any non-"production"
    spelling ran local code.
    """
    return os.environ.get("KUBONA_ENV", "").strip().lower() in _DEV_ENV_VALUES


def build_container_command(*, image: str, workdir: str, max_memory_mb: int,
                            cpus: str = SANDBOX_CPUS,
                            pids_limit: int = SANDBOX_PIDS_LIMIT,
                            seccomp_profile: str | None = None) -> list[str]:
    """The exact container invocation (unit-tested flag-for-flag).

    Parity with the Go rail's hardened ephemeral config
    (platform/core/pkg/sandbox/docker.go :: ExecuteHarness): read-only
    rootfs, hardened tmpfs, ALL capabilities dropped, no-new-privileges, the
    shipped seccomp profile, no network, memory+swap/cpu/pids caps,
    unprivileged --user, read-only bind of the workload dir, unbuffered
    output, pinned entrypoint. seccomp_profile=None (the default) resolves
    to the shipped platform/bridge/seccomp-profile.json via
    _default_seccomp_profile() and raises FileNotFoundError when it is
    absent (fail closed — the caller refuses the run); pass an explicit
    profile path for an operator custom profile; pass "" ONLY for the
    Docker-default differential in tests (proves the backstop matters — it
    is never used by execute_script, which has no profile-less path). We
    never pass seccomp=unconfined.
    """
    if seccomp_profile is None:
        seccomp_profile = _default_seccomp_profile()
        if seccomp_profile is None:
            raise FileNotFoundError(
                "shipped seccomp profile absent: refusing to build a "
                "profile-less container invocation (no silent fallback to "
                "Docker's default profile)")
    mem = f"{max_memory_mb}m"
    cmd = [
        "docker", "run", "--rm",
        "--read-only",
        "--tmpfs", SANDBOX_TMPFS,
        "--cap-drop=ALL",
        "--security-opt=no-new-privileges",
    ]
    if seccomp_profile:
        cmd += ["--security-opt", f"seccomp={seccomp_profile}"]
    cmd += [
        "--network", "none",
        "--memory", mem,
        "--memory-swap", mem,
        "--cpus", cpus,
        f"--pids-limit={pids_limit}",
        "--user", SANDBOX_USER,
        "-v", f"{workdir}:/work:ro",
        "-w", "/work",
        "-e", "PYTHONUNBUFFERED=1",
        "--entrypoint", "python3",
        image, "workload.py",
    ]
    return cmd


class WorkloadSandbox:
    """Static and dynamic sandbox for agent code execution."""

    def __init__(
        self,
        max_cpu_seconds: int = 5,
        max_memory_mb: int = 512,
        allowed_modules: set[str] | None = None,
    ):
        self.max_cpu_seconds = max_cpu_seconds
        self.max_memory_mb = max_memory_mb
        self.allowed_modules = set(allowed_modules) if allowed_modules is not None else set(ALLOWED_MODULES)

    def validate_ast(self, code_str: str) -> None:
        """Inspects Python code AST and rejects forbidden imports, dangerous
        builtins, and dunder/introspection escapes (W2.15)."""
        try:
            tree = ast.parse(code_str)
        except SyntaxError as e:
            raise SecurityPolicyViolation(f"Syntax error: {e}") from e

        for node in ast.walk(tree):
            # Check import x
            if isinstance(node, ast.Import):
                for alias in node.names:
                    root_pkg = alias.name.split(".")[0]
                    if root_pkg in BLOCKED_MODULES or alias.name in BLOCKED_MODULES:
                        raise SecurityPolicyViolation(f"Disallowed import: '{alias.name}'")
                    if root_pkg not in self.allowed_modules:
                        raise SecurityPolicyViolation(f"Disallowed import: '{alias.name}'")

            # Check from x import y
            elif isinstance(node, ast.ImportFrom):
                if getattr(node, "level", 0) > 0:
                    raise SecurityPolicyViolation("Relative imports are disallowed in sandbox")
                if node.module:
                    root_pkg = node.module.split(".")[0]
                    if root_pkg in BLOCKED_MODULES or node.module in BLOCKED_MODULES:
                        raise SecurityPolicyViolation(f"Disallowed import from: '{node.module}'")
                    if root_pkg not in self.allowed_modules:
                        raise SecurityPolicyViolation(f"Disallowed import from: '{node.module}'")
                else:
                    raise SecurityPolicyViolation("Import without module is disallowed in sandbox")
                for alias in node.names:
                    # Smuggled-submodule reach (P1): `from scipy import io` /
                    # `from numpy import f2py` bypass a root-only check — the
                    # root is allowlisted, so refuse the qualified module.
                    # Checked FIRST for a precise refusal naming the module.
                    if node.module and f"{node.module}.{alias.name}" in BLOCKED_MODULES:
                        raise SecurityPolicyViolation(
                            f"Disallowed import from: '{node.module}.{alias.name}'")
                    if alias.name in _BLOCKED_ATTRS or (
                            alias.name.startswith("__") and alias.name.endswith("__")):
                        raise SecurityPolicyViolation(
                            f"Disallowed dunder import: '{alias.name}'")

            # Check calls to dangerous builtins like eval, exec, __import__
            elif isinstance(node, ast.Call):
                if isinstance(node.func, ast.Name):
                    if node.func.id in _BLOCKED_CALLS:
                        raise SecurityPolicyViolation(f"Disallowed call to builtin '{node.func.id}()'")
                elif isinstance(node.func, ast.Attribute):
                    # importlib.import_module(...), os.system(...),
                    # module.__class__ traversals spelled as calls — refuse the
                    # attribute path, not just the bare name.
                    if node.func.attr in _BLOCKED_ATTRS or node.func.attr in _BLOCKED_CALLS:
                        raise SecurityPolicyViolation(
                            f"Disallowed attribute call '.{node.func.attr}()'")

            # Check attribute escapes: x.__class__, x.__mro__, x.__subclasses__
            elif isinstance(node, ast.Attribute):
                if node.attr in _BLOCKED_ATTRS:
                    raise SecurityPolicyViolation(
                        f"Disallowed dunder attribute access '.{node.attr}'")
                # Fail-closed over clever (P1): any non-benign dunder
                # attribute refuses — frame/function/module reach
                # (`__traceback__`, `__self__`, `__loader__`, ...) closes here
                # instead of one name at a time.
                if (node.attr.startswith("__") and node.attr.endswith("__")
                        and node.attr not in _BENIGN_DUNDER_ATTRS):
                    raise SecurityPolicyViolation(
                        f"Disallowed dunder attribute access '.{node.attr}' "
                        "(not on the benign allowlist: __name__, __doc__, __version__)")

    def execute_script(self, code_str: str, timeout_sec: float = 10.0) -> SandboxResult:
        """Validates AST and executes with resource constraints.

        Routing (Phase-1 hardening):
        * KUBONA_SANDBOX_CONTAINER=1 → the pinned container with Go-parity
          hardening (dev and production). A missing daemon refuses with
          `isolation_unavailable` — never a silent local fallback.
        * Otherwise in production (or on an unknown KUBONA_ENV spelling) →
          refuse with `isolation_required`. KUBONA_SANDBOX_UNSAFE_LOCAL=1
          NEVER re-enables local execution in production.
        * Otherwise in dev WITHOUT KUBONA_SANDBOX_UNSAFE_LOCAL=1 → refuse
          with `unsafe_local_disabled` (container-only dev setups fail
          loudly; the historic unset-permits-local default is gone —
          Phase-2 deny-by-default).
        * Otherwise (dev WITH KUBONA_SANDBOX_UNSAFE_LOCAL=1) → the hermetic
          local runner: AST gate, rlimit
          clamps, scrubbed environment, capped output. NOT a security
          boundary — acknowledged dev-only via KUBONA_SANDBOX_UNSAFE_LOCAL.
        """
        if os.getenv(SANDBOX_CONTAINER_ENV) == "1":
            # The container rail (dev AND production): AST pre-gate, then the
            # pinned image. No host fallback — a missing daemon/image
            # refuses instead of running locally.
            try:
                self.validate_ast(code_str)
            except SecurityPolicyViolation as exc:
                return SandboxResult(
                    success=False,
                    returncode=-1,
                    stdout="",
                    stderr=str(exc),
                    violation=str(exc),
                )
            with tempfile.TemporaryDirectory(prefix="kubona-sandbox-") as tmpdir:
                script_path = os.path.join(tmpdir, "workload.py")
                with open(script_path, "w") as f:
                    f.write(_SANDBOX_PREAMBLE + code_str)

                # The container runs as UID 1000 (sandbox); a 0700 host
                # tmpdir bind-mounts as unreadable on a real Linux runner
                # (Docker Desktop masks this locally). Grant read-only.
                os.chmod(tmpdir, 0o755)
                os.chmod(script_path, 0o644)
                image = os.getenv(SANDBOX_IMAGE_ENV, SANDBOX_IMAGE_DEFAULT)
                if shutil.which("docker") is None:
                    return SandboxResult(success=False, returncode=-1, stdout="",
                                         stderr=(f"docker is not available for container sandbox "
                                                 f"(image {image!r}): refusing host-side execution"),
                                         violation="isolation_unavailable")
                # Default-on (Phase-2): the shipped profile applies unless
                # the operator points at a custom file. No disable exists;
                # a missing profile refuses the run (fail closed).
                seccomp_profile = (os.getenv(SANDBOX_SECCOMP_PROFILE_ENV)
                                   or _default_seccomp_profile())
                if seccomp_profile is None:
                    return SandboxResult(
                        success=False, returncode=-1, stdout="",
                        stderr=("shipped seccomp profile absent and no "
                                f"{SANDBOX_SECCOMP_PROFILE_ENV} override: refusing "
                                "container execution without a profile"),
                        violation="isolation_unavailable")
                cmd = build_container_command(image=image, workdir=tmpdir,
                                              max_memory_mb=self.max_memory_mb,
                                              seccomp_profile=seccomp_profile)
                try:
                    proc = subprocess.run(cmd, capture_output=True, text=True,
                                          timeout=timeout_sec)
                except subprocess.TimeoutExpired:
                    return SandboxResult(success=False, returncode=-1, stdout="",
                                         stderr=f"Execution timed out after {timeout_sec}s",
                                         violation="timeout")
                stdout, t1 = _cap(proc.stdout or "")
                stderr, t2 = _cap(proc.stderr or "")
                return SandboxResult(
                    success=(proc.returncode == 0), returncode=proc.returncode,
                    stdout=stdout, stderr=stderr,
                    truncated=t1 or t2,
                    violation=None if proc.returncode == 0 else "nonzero_exit",
                )

        if not _is_explicit_dev_environment():
            # Production posture (Phase-1): the AST + rlimit path is NOT a
            # security boundary, so it is refused here — in production AND on
            # unknown KUBONA_ENV spellings (fail closed). The unsafe-local
            # flag is dev-only acknowledgement, never a production bypass:
            # this refusal holds regardless of its value.
            return SandboxResult(
                success=False, returncode=-1, stdout="",
                stderr=("sandbox isolation required: set KUBONA_SANDBOX_CONTAINER=1 "
                        f"and {SANDBOX_IMAGE_ENV}={SANDBOX_IMAGE_DEFAULT}; the AST/rlimit "
                        "path is not a security boundary and "
                        f"{SANDBOX_UNSAFE_LOCAL_ENV} never enables it in production"),
                violation="isolation_required",
            )

        if os.getenv(SANDBOX_UNSAFE_LOCAL_ENV) != "1":
            # Deny-by-default (Phase-2): the hermetic local runner requires
            # explicit acknowledgement. Unset, "", "0", or any other spelling
            # refuses with unsafe_local_disabled so container-only dev setups
            # fail loudly instead of silently falling back to local runs.
            return SandboxResult(
                success=False, returncode=-1, stdout="",
                stderr=(f"sandbox local execution requires explicit acknowledgement "
                        f"({SANDBOX_UNSAFE_LOCAL_ENV}=1): "
                        f"set {SANDBOX_CONTAINER_ENV}=1 with {SANDBOX_IMAGE_ENV} for "
                        "container isolation, or set "
                        f"{SANDBOX_UNSAFE_LOCAL_ENV}=1 to acknowledge dev-only local execution"),
                violation="unsafe_local_disabled",
            )

        try:
            self.validate_ast(code_str)
        except SecurityPolicyViolation as exc:
            return SandboxResult(
                success=False,
                returncode=-1,
                stdout="",
                stderr=str(exc),
                violation=str(exc),
            )

        def _preexec_fn():
            if not _HAS_RESOURCE:  # pragma: no cover — Windows: no setrlimit
                return
            # CPU time limit
            resource.setrlimit(resource.RLIMIT_CPU, (self.max_cpu_seconds, self.max_cpu_seconds + 1))
            # Memory address space limit (bytes)
            mem_bytes = self.max_memory_mb * 1024 * 1024
            try:
                resource.setrlimit(resource.RLIMIT_AS, (mem_bytes, mem_bytes))
            except (ValueError, OSError):
                pass  # In some macOS environments RLIMIT_AS has restricted ranges
            for limit, value in (
                (getattr(resource, "RLIMIT_NPROC", None), 64),
                (getattr(resource, "RLIMIT_FSIZE", None), 16 * 1024 * 1024),
                (getattr(resource, "RLIMIT_NOFILE", None), 128),
            ):
                if limit is None:
                    continue
                try:
                    resource.setrlimit(limit, (value, value))
                except (ValueError, OSError):
                    pass

        # W2.15: TemporaryDirectory owns cleanup — no NamedTemporaryFile
        # delete=False + unlink race (a crash between write and unlink leaked
        # the file; a concurrent reader could win the path).
        #
        # Dev-only rail (see docstring): the AST gate above is NOT a security
        # boundary — numpy/scipy file-I/O and codegen submodules are refused
        # at validation as defense-in-depth, but containment here is
        # rlimits + a scrubbed environment only. Production never reaches
        # this branch (isolation_required above).
        with tempfile.TemporaryDirectory(prefix="kubona-sandbox-") as tmpdir:
            script_path = os.path.join(tmpdir, "workload.py")
            with open(script_path, "w") as f:
                f.write(_SANDBOX_PREAMBLE + code_str)

            try:
                proc = subprocess.Popen(
                    [sys.executable, script_path],
                    preexec_fn=_preexec_fn if (_HAS_RESOURCE and os.name == "posix") else None,
                    start_new_session=(os.name == "posix"),
                    stdout=subprocess.PIPE,
                    stderr=subprocess.PIPE,
                    text=True,
                    env=scrubbed_env(),  # W2.15: allowlist env, KUBONA_* dropped
                )
                try:
                    stdout_raw, stderr_raw = proc.communicate(timeout=timeout_sec)
                except subprocess.TimeoutExpired:
                    if os.name == "posix":
                        try:
                            import signal
                            os.killpg(proc.pid, signal.SIGKILL)
                        except ProcessLookupError:
                            pass
                    else:
                        proc.kill()
                    proc.communicate()
                    return SandboxResult(
                        success=False,
                        returncode=-1,
                        stdout="",
                        stderr=f"Execution timed out after {timeout_sec}s",
                        violation="timeout",
                    )
                stdout, t1 = _cap(stdout_raw)
                stderr, t2 = _cap(stderr_raw)
                return SandboxResult(
                    success=(proc.returncode == 0),
                    returncode=proc.returncode,
                    stdout=stdout,
                    stderr=stderr,
                    truncated=(t1 or t2),
                )
            except Exception as exc:
                return SandboxResult(
                    success=False,
                    returncode=-1,
                    stdout="",
                    stderr=str(exc),
                    violation=str(exc),
                )


def _cap(text: str) -> tuple[str, bool]:
    """Cap a stream at MAX_OUTPUT_BYTES (W2.15). Returns (text, truncated)."""
    raw = text.encode("utf-8", errors="replace")
    if len(raw) <= MAX_OUTPUT_BYTES:
        return text, False
    cut = raw[:MAX_OUTPUT_BYTES].decode("utf-8", errors="ignore")
    return cut + f"\n[truncated at {MAX_OUTPUT_BYTES} bytes]", True
