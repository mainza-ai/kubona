import * as ed from '@noble/ed25519';
import { sha256 } from '@noble/hashes/sha2.js';
import { bytesToHex, utf8ToBytes } from '@noble/hashes/utils.js';
import { signWithCustody, type CustodySigner } from './custody';

// Tenant-admin mutation envelope (U1-b), mirroring Go byte-for-byte:
//   tenants.AdminAction{tenant_id, action, params_hash, expiry,
//                       pubkey_hex, signature_hex}
//   CanonicalPayload = "tenant|action|params_hash|expiry" with expiry in
//   UTC seconds ("2006-01-02T15:04:05Z").
//   ParamsHash = hex(sha256(json.Marshal(params))) — Go sorts map keys,
//   so this builder sorts keys too; numbers use Go float formatting.
// Golden vectors (generated by the Go toolchain 2026-10-17, pinned in
// adminAction.test.ts — never hand-edited).

export interface AdminAction {
  tenant_id: string;
  action: string;
  params_hash: string;
  expiry: string;
  pubkey_hex: string;
  signature_hex: string;
}

export type AdminParams = Record<string, number | string>;

// Go float formatting for JSON: integers render bare (150, never 150.0),
// decimals shortest-round-trip (49.5). Operator-entered money values are
// cents-scale decimals where both encoders agree — pinned by vectors.
export function goFloat(n: number): string {
  if (!Number.isFinite(n)) throw new Error(`refused: non-finite admin param ${n}`);
  if (Number.isInteger(n)) return String(n);
  return String(n);
}

export function canonicalAdminParams(params: AdminParams): string {
  const keys = Object.keys(params).sort();
  const parts = keys.map((k) => {
    const v = params[k];
    return typeof v === 'number' ? `"${k}":${goFloat(v)}` : `"${k}":${JSON.stringify(v)}`;
  });
  return `{${parts.join(',')}}`;
}

export function adminParamsHash(params: AdminParams): string {
  return bytesToHex(sha256(utf8ToBytes(canonicalAdminParams(params))));
}

export function adminExpiryIso(ttlSeconds = 300): string {
  // UTC seconds precision, matching Go's 2006-01-02T15:04:05Z layout.
  return new Date(Date.now() + ttlSeconds * 1000).toISOString().slice(0, 19) + 'Z';
}

export function adminPayload(tenantId: string, action: string, paramsHash: string, expiryIso: string): string {
  return `${tenantId}|${action}|${paramsHash}|${expiryIso}`;
}

export interface SignAdminActionInput {
  tenantId: string;
  action: 'set_ceiling' | 'set_status' | 'refund_spend' | 'set_admin_key' | 'grant_autonomy' | 'revoke_autonomy';
  params: AdminParams;
  keyPair: { secretKey: Uint8Array; publicKey: Uint8Array };
  ttlSeconds?: number;
}

export interface SignAdminActionCustodyInput {
  tenantId: string;
  action: 'set_ceiling' | 'set_status' | 'refund_spend' | 'set_admin_key' | 'grant_autonomy' | 'revoke_autonomy';
  params: AdminParams;
  ttlSeconds?: number;
}

/** Production path: sign with the non-extractable WebCrypto key. */
export async function signAdminActionWithCustody(input: SignAdminActionCustodyInput): Promise<AdminAction> {
  const tenantId = (input.tenantId || '').trim();
  if (!tenantId) throw new Error('refused: tenant_id is required for an admin action');
  if (!input.action) throw new Error('refused: action is required for an admin action');
  const paramsHash = adminParamsHash(input.params);
  const expiry = adminExpiryIso(input.ttlSeconds);
  const payload = adminPayload(tenantId, input.action, paramsHash, expiry);
  const { publicKeyHex, signature } = await signWithCustody(utf8ToBytes(payload));
  return {
    tenant_id: tenantId,
    action: input.action,
    params_hash: paramsHash,
    expiry,
    pubkey_hex: publicKeyHex,
    signature_hex: bytesToHex(signature),
  };
}

/** Sign with a caller-supplied signer (used for rotation before commit). */
export async function signAdminActionWithSigner(input: SignAdminActionCustodyInput, signer: CustodySigner): Promise<AdminAction> {
  const tenantId = (input.tenantId || '').trim();
  if (!tenantId) throw new Error('refused: tenant_id is required for an admin action');
  if (!input.action) throw new Error('refused: action is required for an admin action');
  const paramsHash = adminParamsHash(input.params);
  const expiry = adminExpiryIso(input.ttlSeconds);
  const payload = adminPayload(tenantId, input.action, paramsHash, expiry);
  const signature = await signer.sign(utf8ToBytes(payload));
  return {
    tenant_id: tenantId,
    action: input.action,
    params_hash: paramsHash,
    expiry,
    pubkey_hex: signer.publicKeyHex,
    signature_hex: bytesToHex(signature),
  };
}

// Legacy explicit-keypair path (tests and deliberate key injection). UI
// Legacy explicit-keypair path (tests and deliberate key injection). UI
// production flows use signAdminActionWithCustody above; do not call this
// with a raw in-memory secret in a production surface.
export function signAdminAction(input: SignAdminActionInput): AdminAction {
  const tenantId = (input.tenantId || '').trim();
  if (!tenantId) throw new Error('refused: tenant_id is required for an admin action');
  if (!input.action) throw new Error('refused: action is required for an admin action');
  const paramsHash = adminParamsHash(input.params);
  const expiry = adminExpiryIso(input.ttlSeconds);
  const payload = adminPayload(tenantId, input.action, paramsHash, expiry);
  const sig = ed.sign(utf8ToBytes(payload), input.keyPair.secretKey);
  return {
    tenant_id: tenantId,
    action: input.action,
    params_hash: paramsHash,
    expiry,
    pubkey_hex: bytesToHex(input.keyPair.publicKey),
    signature_hex: bytesToHex(sig),
  };
}
