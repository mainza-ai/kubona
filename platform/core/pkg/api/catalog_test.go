package api

// R5/C5 tool catalog: the generated surface (build-time, digest-pinned)
// the capabilities endpoint embeds. Run with -update to regenerate after
// intentional tool changes; CI runs WITHOUT it and fails on drift.
//
//	regen: go test ./pkg/api/ -run TestToolCatalogMatchesCheckedIn -update
//
// (from platform/core).

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"flag"
	"net/http"
	"net/http/httptest"
	"os"
	"path/filepath"
	"testing"

	"github.com/mainza-ai/kubona/core/pkg/jobs"
	"github.com/mainza-ai/kubona/core/pkg/ledger"
	"github.com/mainza-ai/kubona/core/pkg/session"
	"github.com/mainza-ai/kubona/core/pkg/supervisor"
	"github.com/mainza-ai/kubona/core/pkg/tools"
	"github.com/mainza-ai/kubona/core/pkg/watchdog"
)

var updateCatalog = flag.Bool("update", false, "regenerate the checked-in tool catalog + digest")

type toolCatalog struct {
	GeneratedBy string           `json:"generated_by"`
	Digest      string           `json:"digest"`
	Tools       []tools.Snapshot `json:"tools"`
}

// buildLiveCatalog renders the production registry canonically via the
// single-source tools.CatalogJSON (the SAME bytes the capabilities
// endpoint digests — algorithm skew is impossible, only staleness).
func buildLiveCatalog(t *testing.T) ([]byte, string) {
	t.Helper()
	t.Setenv("KUBONA_ALLOW_EPHEMERAL_SIGNER", "1")
	l, err := ledger.OpenLedger(t.TempDir() + "/catalog.db")
	if err != nil {
		t.Fatalf("open: %v", err)
	}
	defer l.Close()
	sm := session.NewManager(l)
	jr := jobs.NewRunner(l, nil, 1)
	sup := supervisor.NewSupervisor(l)
	wd := watchdog.NewTaskWatchdog(l, sup)
	srv := NewServer(l, sm, jr, sup, wd)

	body, digest := tools.CatalogJSON(srv.toolRegistry.Catalog())
	if body == nil {
		t.Fatal("catalog marshal failed")
	}
	return body, digest
}

func checkedInCatalogPath() string {
	return filepath.Join("..", "..", "..", "contracts", "tool-catalog.json")
}

func TestToolCatalogMatchesCheckedIn(t *testing.T) {
	body, digest := buildLiveCatalog(t)
	if *updateCatalog {
		doc, _ := json.MarshalIndent(map[string]any{
			"generated_by": "go test ./pkg/api/ -run TestToolCatalogMatchesCheckedIn -update",
			"digest":       digest,
			"tools":        json.RawMessage(body),
		}, "", "  ")
		if err := os.WriteFile(checkedInCatalogPath(), append(doc, '\n'), 0o644); err != nil {
			t.Fatalf("write catalog: %v", err)
		}
		gen := "// Code generated by TestToolCatalogMatchesCheckedIn -update. DO NOT EDIT.\n\npackage api\n\n// EmbeddedCatalogDigest pins the reviewed tool surface at build time.\n// The capabilities endpoint 500s when the live registry disagrees\n// (fail-closed discovery: regen, never hand-edit).\nconst EmbeddedCatalogDigest = \"" + digest + "\"\n"
		if err := os.WriteFile("catalog_digest.go", []byte(gen), 0o644); err != nil {
			t.Fatalf("write digest: %v", err)
		}
		t.Logf("catalog regenerated: %s", digest)
		return
	}
	raw, err := os.ReadFile(checkedInCatalogPath())
	if err != nil {
		t.Fatalf("reading checked-in catalog (run with -update to generate): %v", err)
	}
	var checked toolCatalog
	if err := json.Unmarshal(raw, &checked); err != nil {
		t.Fatalf("parsing checked-in catalog: %v", err)
	}
	if checked.Digest != digest {
		t.Fatalf("tool catalog drift: live registry digests %s, checked-in %s — regen with -update after intentional tool changes", digest, checked.Digest)
	}
	liveTools, _ := json.Marshal(checked.Tools)
	sum := sha256.Sum256(liveTools)
	if hex.EncodeToString(sum[:]) != checked.Digest {
		t.Fatal("checked-in digest does not match checked-in tools (hand-edit detected: regen, never hand-edit)")
	}
	if EmbeddedCatalogDigest != checked.Digest {
		t.Fatal("embedded digest const drifts from the checked-in file (regen with -update)")
	}
}

func TestCapabilitiesSkew500s(t *testing.T) {
	// C5 fail-closed discovery: a registry that disagrees with the
	// reviewed pinned digest serves 500, never stale tools.
	t.Setenv("KUBONA_ALLOW_EPHEMERAL_SIGNER", "1")
	l, err := ledger.OpenLedger(t.TempDir() + "/skew.db")
	if err != nil {
		t.Fatalf("open: %v", err)
	}
	defer l.Close()
	sm := session.NewManager(l)
	jr := jobs.NewRunner(l, nil, 1)
	sup := supervisor.NewSupervisor(l)
	wd := watchdog.NewTaskWatchdog(l, sup)
	srv := NewServer(l, sm, jr, sup, wd)
	if err := srv.toolRegistry.Register(tools.Definition{
		Name: "unreviewed_tool", Capability: "test:write",
		Parameters: map[string]any{"type": "object"},
		Handler: func(ctx context.Context, args json.RawMessage) (any, error) {
			return nil, nil
		},
	}); err != nil {
		t.Fatalf("register rogue tool: %v", err)
	}
	req := httptest.NewRequest(http.MethodGet, "/api/capabilities", nil)
	w := httptest.NewRecorder()
	srv.Handler().ServeHTTP(w, req)
	if w.Code != http.StatusInternalServerError {
		t.Fatalf("skewed registry must 500, got %d", w.Code)
	}
	var body map[string]any
	if err := json.Unmarshal(w.Body.Bytes(), &body); err != nil || body["code"] != "internal" {
		t.Fatalf("skew 500 must be typed internal: %s", w.Body.String())
	}
}
