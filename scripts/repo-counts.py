#!/usr/bin/env python3
"""Generate or check the repository's public counts.

The README and wiki used to carry hand-maintained route/test counts. They
drifted. This script is the single source of truth: run `--write` after a
change that moves a count, and let CI fail on `--check` when the generated
file is stale.

Counts are source-derived and deliberately conservative:
- routes: `s.route("...")` registrations in the Go API server.
- Go packages: directories under platform/core that contain .go files.
- Go test funcs: top-level `func Test...` declarations in *_test.go.
- Python test files: test_*.py under platform/tests.
- console test files/cases: *.test.ts(x) and `it(`/`test(` declarations.
- Rust tests: `#[test]` attributes.
- MCP servers/tools: the reviewed catalog JSON.
- wiki pages: markdown files under wiki/.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "repo-counts.md"


def fail(message: str) -> "NoReturn":
    print(f"repo-counts: {message}", file=sys.stderr)
    raise SystemExit(2)


def read(path: Path) -> str:
    if not path.exists():
        fail(f"missing {path.relative_to(ROOT)}")
    return path.read_text(encoding="utf-8")


def count_routes() -> int:
    text = read(ROOT / "platform/core/pkg/api/server.go")
    return len(re.findall(r's\.route\(\s*"', text))


def count_go_packages() -> int:
    dirs = {
        p.parent
        for p in (ROOT / "platform/core").rglob("*.go")
        if "vendor" not in p.parts
    }
    return len(dirs)


def count_go_test_funcs() -> int:
    total = 0
    for p in (ROOT / "platform/core").rglob("*_test.go"):
        total += len(re.findall(r"^func Test", p.read_text(encoding="utf-8"), re.M))
    return total


def count_python_test_files() -> int:
    return len(list((ROOT / "platform/tests").rglob("test_*.py")))


def count_console_tests() -> tuple[int, int]:
    files = list((ROOT / "platform/console/src").rglob("*.test.ts"))
    files += list((ROOT / "platform/console/src").rglob("*.test.tsx"))
    cases = 0
    for p in files:
        cases += len(re.findall(r"^\s*(?:it|test)\s*\(", p.read_text(encoding="utf-8"), re.M))
    return len(files), cases


def count_rust_tests() -> int:
    total = 0
    for p in (ROOT / "platform/crates").rglob("*.rs"):
        total += len(re.findall(r"#\[test\]", p.read_text(encoding="utf-8")))
    return total


def count_mcp() -> tuple[int, int]:
    data = json.loads(read(ROOT / "platform/contracts/mcp-catalog.json"))
    tools = data.get("tools", [])
    servers = {t.get("server") for t in tools if t.get("server")}
    return len(servers), len(tools)


def count_wiki_pages() -> int:
    return len(list((ROOT / "wiki").rglob("*.md")))


def render() -> str:
    servers, tools = count_mcp()
    console_files, console_cases = count_console_tests()
    rows = [
        ("HTTP routes (Go API)", count_routes(), "s.route registrations in `platform/core/pkg/api/server.go`"),
        ("Go packages", count_go_packages(), "directories under `platform/core` containing `.go` files"),
        ("Go test functions", count_go_test_funcs(), "top-level `func Test...` in `*_test.go`"),
        ("Python test files", count_python_test_files(), "`test_*.py` under `platform/tests`"),
        ("Console test files", console_files, "`*.test.ts` / `*.test.tsx` under `platform/console/src`"),
        ("Console test cases", console_cases, "`it(` / `test(` declarations in console test files"),
        ("Rust tests", count_rust_tests(), "`#[test]` attributes under `platform/crates`"),
        ("MCP servers", servers, "reviewed `platform/contracts/mcp-catalog.json`"),
        ("MCP tools", tools, "reviewed `platform/contracts/mcp-catalog.json`"),
        ("Wiki pages", count_wiki_pages(), "markdown files under `wiki/`"),
    ]
    lines = [
        "# Repository counts",
        "",
        "Generated by `python3 scripts/repo-counts.py --write`. Do not edit by hand.",
        "CI runs `python3 scripts/repo-counts.py --check` and fails when this file is stale.",
        "",
        "| Metric | Value | Source |",
        "|---|---:|---|",
    ]
    lines += [f"| {name} | {value} | {source} |" for name, value, source in rows]
    lines += [
        "",
        "The console case count is a source-level count. Vitest is the runtime authority;",
        "when it differs, regenerate this file and note the runtime count in the change.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--write", action="store_true", help="write docs/repo-counts.md")
    group.add_argument("--check", action="store_true", help="fail if docs/repo-counts.md is stale")
    args = parser.parse_args()

    expected = render()
    if args.write:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(expected, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}")
        return 0
    if args.check:
        if not OUT.exists():
            fail(f"{OUT.relative_to(ROOT)} is missing; run --write")
        actual = OUT.read_text(encoding="utf-8")
        if actual != expected:
            print("repo-counts: docs/repo-counts.md is stale; run:", file=sys.stderr)
            print("  python3 scripts/repo-counts.py --write", file=sys.stderr)
            import difflib

            diff = difflib.unified_diff(
                actual.splitlines(),
                expected.splitlines(),
                fromfile="docs/repo-counts.md",
                tofile="generated",
                lineterm="",
            )
            print("\n".join(diff), file=sys.stderr)
            return 1
        print("repo-counts: OK")
        return 0

    parser.print_help()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
