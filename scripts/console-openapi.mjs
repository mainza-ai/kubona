#!/usr/bin/env node
// Generate OpenAPI 3.1 for the modeled console endpoints from:
//   - platform/contracts/console-contract-inventory.json (paths/methods)
//   - platform/console/src/lib/responseContract.ts (response schemas)
//
// Unmodeled API functions are named explicitly at the document root; they are
// not silently presented as documented operations. Run --write to regenerate,
// --check to enforce freshness in CI.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CONSOLE = path.join(ROOT, 'platform', 'console');
const INVENTORY = path.join(ROOT, 'platform', 'contracts', 'console-contract-inventory.json');
const CONTRACT = path.join(CONSOLE, 'src', 'lib', 'responseContract.ts');
const OUT = path.join(ROOT, 'platform', 'contracts', 'console-openapi.json');
const TS_OUT = path.join(CONSOLE, 'src', 'lib', 'generated', 'openapi.ts');
const require = createRequire(path.join(CONSOLE, 'package.json'));
const ts = require('typescript');

function loadSchemas() {
  const source = fs.readFileSync(CONTRACT, 'utf8');
  const js = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
  }).outputText;
  const mod = { exports: {} };
  const fn = new Function('exports', 'require', 'module', '__filename', '__dirname', js);
  fn(mod.exports, require, mod, CONTRACT, path.dirname(CONTRACT));
  if (!mod.exports.RESPONSE_SCHEMAS) throw new Error('RESPONSE_SCHEMAS missing');
  return mod.exports.RESPONSE_SCHEMAS;
}

function toJsonSchema(schema) {
  if (!schema || typeof schema !== 'object') return {};
  if (schema.type === 'any') return {};
  const out = { type: schema.type };
  if (schema.nullable) out.nullable = true;
  if (schema.required) out.required = schema.required;
  if (schema.properties) {
    out.properties = {};
    for (const [key, value] of Object.entries(schema.properties)) out.properties[key] = toJsonSchema(value);
  }
  if (schema.items) out.items = toJsonSchema(schema.items);
  return out;
}

function operationId(name) {
  return name.replace(/[^A-Za-z0-9_]/g, '_');
}

function typeName(name) {
  const clean = name.replace(/[^A-Za-z0-9]+/g, ' ').trim().split(/\s+/);
  const joined = clean.map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join('');
  return /^[0-9]/.test(joined) ? `Schema${joined}` : joined || 'Schema';
}

function tsType(schema) {
  if (!schema || typeof schema !== 'object' || schema.type === 'any') return 'unknown';
  let base;
  switch (schema.type) {
    case 'string':
      base = 'string';
      break;
    case 'number':
    case 'integer':
      base = 'number';
      break;
    case 'boolean':
      base = 'boolean';
      break;
    case 'array':
      base = `${tsType(schema.items)}[]`;
      break;
    case 'object': {
      if (!schema.properties || Object.keys(schema.properties).length === 0) {
        base = 'Record<string, unknown>';
        break;
      }
      const required = new Set(schema.required || []);
      const fields = Object.entries(schema.properties)
        .map(([name, value]) => `  ${JSON.stringify(name)}${required.has(name) ? '' : '?'}: ${tsType(value)};`)
        .join('\n');
      base = `{\n${fields}\n}`;
      break;
    }
    default:
      base = 'unknown';
  }
  return schema.nullable ? `${base} | null` : base;
}

function renderTypes(components, operations) {
  const lines = [
    '// Generated by scripts/console-openapi.mjs. Do not edit.',
    '// Source: platform/contracts/console-openapi.json + responseContract schemas.',
    '',
  ];
  for (const [name, schema] of Object.entries(components)) {
    lines.push(`export type ${typeName(name)} = ${tsType(schema)};`, '');
  }
  lines.push('export type ApiOperationResponse = {');
  for (const op of operations) {
    lines.push(`  ${op.operationId}: ${typeName(op.contract)};`);
  }
  lines.push('};', '');
  lines.push('export const API_OPERATIONS = {');
  for (const op of operations) {
    lines.push(`  ${op.operationId}: { method: ${JSON.stringify(op.method)}, path: ${JSON.stringify(op.path)}, response: ${JSON.stringify(op.contract)} },`);
  }
  lines.push('} as const;', '');
  lines.push('export type ApiOperationName = keyof typeof API_OPERATIONS;', '');
  return lines.join('\n');
}

function main() {
  const inventory = JSON.parse(fs.readFileSync(INVENTORY, 'utf8'));
  const schemas = loadSchemas();
  const components = {};
  for (const [name, schema] of Object.entries(schemas)) components[name] = toJsonSchema(schema);

  const paths = {};
  const used = new Map();
  const operations = [];
  for (const fn of inventory.modeled_functions) {
    if (!fn.path || !fn.method) continue;
    const openapiPath = fn.path.replace(/:([A-Za-z0-9_]+)/g, '{$1}');
    paths[openapiPath] ??= {};
    const key = `${fn.method} ${openapiPath}`;
    if (used.has(key)) {
      const existing = used.get(key);
      if (existing !== fn.contract) {
        throw new Error(`console-openapi: ${key} has conflicting contracts ${existing} and ${fn.contract}`);
      }
      continue;
    }
    used.set(key, fn.contract);
    operations.push({ operationId: operationId(fn.function), method: fn.method.toLowerCase(), path: openapiPath, contract: fn.contract });
    const params = [...openapiPath.matchAll(/\{([^}]+)\}/g)].map((m) => ({
      name: m[1],
      in: 'path',
      required: true,
      schema: { type: 'string' },
    }));
    paths[openapiPath][fn.method.toLowerCase()] = {
      operationId: operationId(fn.function),
      tags: [openapiPath.split('/')[2] || 'api'],
      ...(params.length ? { parameters: params } : {}),
      responses: {
        '200': {
          description: `Response contract: ${fn.contract}`,
          content: {
            'application/json': {
              schema: { $ref: `#/components/schemas/${fn.contract}` },
            },
          },
        },
      },
    };
  }

  const doc = {
    openapi: '3.1.0',
    info: {
      title: 'Kubona Console API',
      version: '1.0.0',
      description:
        'Generated from the console contract inventory. Modeled operations and response schemas are documented; client-only helpers and any unmodeled functions are listed explicitly.',
    },
    paths,
    components: { schemas: components },
    'x-kubona-unmodeled-functions': inventory.unmodeled_functions.map((f) => f.function),
    'x-kubona-client-only-functions': (inventory.client_only_functions || []).map((f) => f.function),
  };
  const rendered = JSON.stringify(doc, null, 2) + '\n';
  const renderedTypes = renderTypes(components, operations);
  if (process.argv.includes('--check')) {
    for (const [file, expected] of [[OUT, rendered], [TS_OUT, renderedTypes]]) {
      if (!fs.existsSync(file)) {
        console.error(`console-openapi: missing ${path.relative(ROOT, file)}`);
        process.exit(1);
      }
      if (fs.readFileSync(file, 'utf8') !== expected) {
        console.error(`console-openapi: ${path.relative(ROOT, file)} is stale; run node scripts/console-openapi.mjs --write`);
        process.exit(1);
      }
    }
    console.log(`console-openapi: ${Object.keys(paths).length} paths, ${Object.keys(components).length} schemas, ${doc['x-kubona-unmodeled-functions'].length} unmodeled, ${doc['x-kubona-client-only-functions'].length} client-only`);
    return;
  }
  fs.mkdirSync(path.dirname(TS_OUT), { recursive: true });
  fs.writeFileSync(OUT, rendered);
  fs.writeFileSync(TS_OUT, renderedTypes);
  console.log(`console-openapi: wrote ${path.relative(ROOT, OUT)} and ${path.relative(ROOT, TS_OUT)}`);
}

main();
